package com.arinara.photos.theme

import androidx.compose.ui.unit.dp

/**
 * Standardized spacing tokens with 8dp grid system and 4dp sub-multiples:
 * - Micro: 4.dp
 * - Small: 8.dp
 * - Compact: 12.dp
 * - Medium: 16.dp
 * - Large: 20.dp
 * - Section: 24.dp
 * - Macro: 32.dp
 * - MajorSection: 48.dp
 * - Huge: 64.dp
 * - BottomClearance: 100.dp (mandatory clearance above floating dock)
 */
object PhotosSpacing {
    val Micro = 4.dp
    val Small = 8.dp
    val Compact = 12.dp
    val Medium = 16.dp
    val Large = 20.dp
    val Section = 24.dp
    val Macro = 32.dp
    val MajorSection = 48.dp
    val Huge = 64.dp
    val BottomClearance = 100.dp
}
